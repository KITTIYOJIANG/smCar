from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import torch


DEFAULT_CONFIG = Path("roi_config.json")
DEFAULT_DATASET = "class"
DEFAULT_SPLIT_ROOT = Path("reports")
DEFAULT_MODEL_ROOT = Path("models")


def run_command(command: list[str]) -> None:
    print("$ " + " ".join(command))
    subprocess.run(command, check=True)


def read_config(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def dataset_config(config: dict, dataset: str) -> dict:
    datasets = config.get("datasets", {})
    if dataset not in datasets:
        available = ", ".join(sorted(datasets))
        raise SystemExit(f"dataset '{dataset}' not found. Available: {available}")
    return dict(datasets[dataset])


def default_tflite_python() -> str:
    bundled = Path(".venv_tflite") / "Scripts" / "python.exe"
    return str(bundled) if bundled.exists() else sys.executable


def labels_from_map(label_map: dict[str, int]) -> list[str]:
    return [label for label, _ in sorted(label_map.items(), key=lambda item: item[1])]


def export_weights_npz(checkpoint_path: Path, package_dir: Path) -> Path:
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    state: dict[str, torch.Tensor] = checkpoint["model_state"]
    input_size = int(checkpoint.get("input_size", 128))
    label_map: dict[str, int] = checkpoint["label_map"]

    arrays: dict[str, np.ndarray] = {
        name: tensor.detach().cpu().numpy()
        for name, tensor in state.items()
    }
    arrays["__input_size__"] = np.array([input_size], dtype=np.int64)

    package_dir.mkdir(parents=True, exist_ok=True)
    weights_path = package_dir / "classifier_v3_weights_np.npz"
    np.savez(weights_path, **arrays)
    (package_dir / "label_map.json").write_text(
        json.dumps(label_map, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    (package_dir / "labels.txt").write_text(
        "\n".join(labels_from_map(label_map)) + "\n",
        encoding="utf-8",
    )
    shutil.copy2(checkpoint_path, package_dir / "best_model.pt")
    return weights_path


def copy_openmv_files(package_dir: Path, main_source: Path) -> None:
    openmv_dir = package_dir / "openmv_files"
    openmv_dir.mkdir(parents=True, exist_ok=True)
    for name in ("classifier.tflite", "labels.txt", "roi_runtime_config.py"):
        src = package_dir / name
        if src.exists():
            shutil.copy2(src, openmv_dir / name)
    if main_source.exists():
        shutil.copy2(main_source, openmv_dir / "main.py")


def scaled_roi(config: dict, roi_name: str, target_width: int, target_height: int) -> tuple[int, int, int, int]:
    frame = config.get("frame", {})
    source_width = int(frame.get("width", target_width))
    source_height = int(frame.get("height", target_height))
    raw = config["rois"][roi_name]
    sx = target_width / max(1, source_width)
    sy = target_height / max(1, source_height)
    return (
        int(round(int(raw["x"]) * sx)),
        int(round(int(raw["y"]) * sy)),
        int(round(int(raw["w"]) * sx)),
        int(round(int(raw["h"]) * sy)),
    )


def write_openmv_runtime_config(config: dict, dataset: dict, package_dir: Path) -> Path:
    classify_roi_name = str(dataset.get("roi", "class_roi"))
    screen_roi = scaled_roi(config, "screen_roi", 320, 240)
    classify_roi = scaled_roi(config, classify_roi_name, 320, 240)
    input_size = int(config.get("model", {}).get("input_size", 128))
    path = package_dir / "roi_runtime_config.py"
    path.write_text(
        "\n".join(
            [
                "# Generated by train_roi_model.py.",
                "# Coordinates are scaled from roi_config.json to OpenMV QVGA.",
                f"MODEL_INPUT_SIZE = {input_size}",
                f"SCREEN_ROI = {screen_roi}",
                f"CLASSIFY_ROI = {classify_roi}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the ROI classifier training and TFLite conversion loop.")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--dataset", default=DEFAULT_DATASET)
    parser.add_argument("--epochs", type=int, default=12)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--input-size", type=int)
    parser.add_argument("--seed", type=int, default=20260626)
    parser.add_argument("--max-per-label", type=int, default=0, help="Crop at most N images per label for smoke tests.")
    parser.add_argument("--max-train-samples", type=int, default=0)
    parser.add_argument("--max-val-samples", type=int, default=0)
    parser.add_argument("--max-test-samples", type=int, default=0)
    parser.add_argument("--split-dir", type=Path)
    parser.add_argument("--train-dir", type=Path)
    parser.add_argument("--package-dir", type=Path)
    parser.add_argument("--train-python", default=sys.executable)
    parser.add_argument("--tflite-python", default=default_tflite_python())
    parser.add_argument("--overwrite-crops", action="store_true")
    parser.add_argument("--skip-crop", action="store_true")
    parser.add_argument("--skip-split", action="store_true")
    parser.add_argument("--skip-train", action="store_true")
    parser.add_argument("--skip-convert", action="store_true")
    parser.add_argument("--representative-limit", type=int, default=512)
    parser.add_argument("--eval-limit", type=int, default=0)
    args = parser.parse_args()

    config = read_config(args.config)
    dataset = dataset_config(config, args.dataset)
    model_config = config.get("model", {})
    input_size = args.input_size or int(model_config.get("input_size", 128))

    crop_output = Path(dataset["output"])
    split_dir = args.split_dir or (DEFAULT_SPLIT_ROOT / f"roi_{args.dataset}_splits")
    train_dir = args.train_dir or (DEFAULT_MODEL_ROOT / f"roi_{args.dataset}_pytorch")
    package_dir = args.package_dir or (DEFAULT_MODEL_ROOT / f"roi_{args.dataset}_tflite")

    if not args.skip_crop:
        crop_command = [
            sys.executable,
            "crop_roi.py",
            "--config",
            str(args.config),
            "--dataset",
            args.dataset,
        ]
        if args.max_per_label > 0:
            crop_command.extend(["--max-per-label", str(args.max_per_label)])
        if args.overwrite_crops:
            crop_command.append("--overwrite")
        run_command(crop_command)

    if not args.skip_split:
        run_command(
            [
                args.train_python,
                "split_dataset.py",
                "--source",
                str(crop_output),
                "--output-dir",
                str(split_dir),
                "--seed",
                str(args.seed),
            ]
        )

    if not args.skip_train:
        train_command = [
            args.train_python,
            "train_classifier.py",
            "--split-dir",
            str(split_dir),
            "--output-dir",
            str(train_dir),
            "--epochs",
            str(args.epochs),
            "--batch-size",
            str(args.batch_size),
            "--input-size",
            str(input_size),
            "--seed",
            str(args.seed),
        ]
        if args.max_train_samples > 0:
            train_command.extend(["--max-train-samples", str(args.max_train_samples)])
        if args.max_val_samples > 0:
            train_command.extend(["--max-val-samples", str(args.max_val_samples)])
        if args.max_test_samples > 0:
            train_command.extend(["--max-test-samples", str(args.max_test_samples)])
        run_command(train_command)

    checkpoint_path = train_dir / "best_model.pt"
    if not checkpoint_path.exists():
        raise SystemExit(f"missing checkpoint: {checkpoint_path}")
    weights_path = export_weights_npz(checkpoint_path, package_dir)
    runtime_config = write_openmv_runtime_config(config, dataset, package_dir)
    print(f"weights_npz={weights_path}")
    print(f"openmv_runtime_config={runtime_config}")

    if not args.skip_convert:
        run_command(
            [
                args.tflite_python,
                "convert_classifier_to_tflite.py",
                "--package-dir",
                str(package_dir),
                "--split-dir",
                str(split_dir),
                "--representative-limit",
                str(args.representative_limit),
                "--eval-limit",
                str(args.eval_limit),
            ]
        )
        copy_openmv_files(package_dir, Path("openmv") / "scripts" / "board" / "classify_character.py")

    print(f"crop_output={crop_output.resolve()}")
    print(f"split_dir={split_dir.resolve()}")
    print(f"train_dir={train_dir.resolve()}")
    print(f"package_dir={package_dir.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
